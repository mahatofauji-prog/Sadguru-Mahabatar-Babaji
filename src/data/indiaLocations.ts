export const getDistrictsForState = (stateName: string): string[] => {
  if (!stateName) return Array.from(new Set(INDIA_STATES_AND_DISTRICTS[0].districts));

  // Exact match
  let found = INDIA_STATES_AND_DISTRICTS.find((s) => s.state === stateName);
  if (found) return Array.from(new Set(found.districts));

  // Normalized substring match
  const normState = stateName.toLowerCase().replace(/[^a-z0-in\u0900-\u097F]/gi, '');
  found = INDIA_STATES_AND_DISTRICTS.find((s) => {
    const norm = s.state.toLowerCase().replace(/[^a-z0-in\u0900-\u097F]/gi, '');
    return norm.includes(normState) || normState.includes(norm);
  });

  if (found) return Array.from(new Set(found.districts));

  return ["अन्य जिला (Other District)"];
};
